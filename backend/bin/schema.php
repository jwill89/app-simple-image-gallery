<?php

declare(strict_types=1);

/**
 * `php bin/schema.php`: regenerate tests/Fixtures/schema.sql, the committed
 * schema, from the migrations run on a throwaway database. SchemaTest fails
 * when the migrations build anything else.
 */

$backend = dirname(__DIR__);
$database = tempnam(sys_get_temp_dir(), 'gallery-schema-');
if ($database === false) {
    fwrite(STDERR, "No temporary file for the throwaway database.\n");
    exit(1);
}

try {
    $php = escapeshellarg(PHP_BINARY);
    $artisan = escapeshellarg("{$backend}/artisan");
    $command = "{$php} {$artisan} migrate --force --no-interaction --database=sqlite";
    $process = proc_open($command, [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, $backend, [...getenv(), 'DB_CONNECTION' => 'sqlite', 'DB_DATABASE' => $database]);
    if (!is_resource($process)) {
        throw new RuntimeException('Could not run the migrations.');
    }
    $output = stream_get_contents($pipes[1]) . stream_get_contents($pipes[2]);
    if (proc_close($process) !== 0) {
        throw new RuntimeException("The migrations failed:\n{$output}");
    }

    $db = new PDO('sqlite:' . $database);
    $objects = $db->query("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY type DESC, name");
    $statements = $objects === false ? [] : $objects->fetchAll(PDO::FETCH_COLUMN);
    $objects = null;
    $db = null;

    $header = <<<'SQL'
        -- The schema the migrations build, generated by `php bin/schema.php` on a throwaway
        -- database; never edited by hand. tests/Feature/Database/SchemaTest.php fails when
        -- a fresh migrate builds anything else, so a migration that changes the schema
        -- changes this file in the same commit.

        SQL;
    file_put_contents("{$backend}/tests/Fixtures/schema.sql", $header . implode(";\n", $statements) . ";\n");
    echo 'Wrote ' . count($statements) . " statements to tests/Fixtures/schema.sql.\n";
} catch (Throwable $e) {
    fwrite(STDERR, $e->getMessage() . "\n");
    exit(1);
} finally {
    $objects = $db = null;
    foreach (['', '-wal', '-shm'] as $suffix) {
        if (is_file($database . $suffix)) {
            unlink($database . $suffix);
        }
    }
}
