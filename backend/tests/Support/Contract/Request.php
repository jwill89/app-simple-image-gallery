<?php

declare(strict_types=1);

namespace Gallery\Tests\Support\Contract;

/**
 * Builders for the request steps in tests/Fixtures/contract-cases.php.
 *
 * A step is an array: method and path, plus any of
 *   json / form / raw (+ contentType) / multipart  the body
 *   auth     'admin' (default for writes) | 'none' (default for reads) |
 *            'expired' | 'captured:<name>' | 'raw:<Authorization value>'
 *   origin   'allowed' (default for writes) | 'dev' | 'foreign' | 'none' (default for reads)
 *   referer  a Referer header
 *   headers  any other request headers
 *   repeat   send this many times and record only the last response
 *   capture  ['<name>' => '<top-level response key>'] for a later 'captured:<name>'
 *
 * A multipart part is ['name' => …] plus 'value', or 'file' (relative to
 * tests/Fixtures) or 'bytes' (that many generated bytes), with optional
 * 'filename' and 'type'.
 */
final class Request
{
    /**
     * @param array<string, mixed> $options
     * @return array<string, mixed>
     */
    public static function get(string $path, array $options = []): array
    {
        return ['method' => 'GET', 'path' => $path] + $options;
    }

    /**
     * @param array<string, mixed> $options
     * @return array<string, mixed>
     */
    public static function post(string $path, array $options = []): array
    {
        return ['method' => 'POST', 'path' => $path] + $options;
    }

    /**
     * @param array<string, mixed> $options
     * @return array<string, mixed>
     */
    public static function put(string $path, array $options = []): array
    {
        return ['method' => 'PUT', 'path' => $path] + $options;
    }

    /**
     * @param array<string, mixed> $options
     * @return array<string, mixed>
     */
    public static function patch(string $path, array $options = []): array
    {
        return ['method' => 'PATCH', 'path' => $path] + $options;
    }

    /**
     * @param array<string, mixed> $options
     * @return array<string, mixed>
     */
    public static function delete(string $path, array $options = []): array
    {
        return ['method' => 'DELETE', 'path' => $path] + $options;
    }

    /**
     * @param array<string, mixed> $options
     * @return array<string, mixed>
     */
    public static function options(string $path, array $options = []): array
    {
        return ['method' => 'OPTIONS', 'path' => $path] + $options;
    }

    /**
     * A multipart file part from tests/Fixtures.
     *
     * @return array<string, mixed>
     */
    public static function file(string $fixture, ?string $filename = null, string $name = 'files[]'): array
    {
        return ['name' => $name, 'file' => $fixture, 'filename' => $filename ?? basename($fixture)];
    }
}
